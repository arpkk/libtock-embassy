// Muchos timers con periodos diferentes y una tarea que ocupa la CPU
#![no_main]
#![no_std]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering::Relaxed};

use embassy_futures::yield_now;
use embassy_time::{Duration, Instant, Timer};
use libtock_embassy as libtock;
use libtock::console::Console;
use libtock::runtime::{set_main, stack_size};

extern crate libtock_debug_panic;

set_main! {main}
stack_size! {0x1000}

const PERIODS_US: [u64; 12] = [
    250, 1000, 1300, 1700, 2300, 2900, 3700, 4100, 5300, 7100, 11000, 130_000,
];
const N: usize = PERIODS_US.len();
const REPORT_S: u64 = 5;

static COUNT: [AtomicU32; N] = [const { AtomicU32::new(0) }; N];
static LATE_US: [AtomicU32; N] = [const { AtomicU32::new(0) }; N];
static SPINS: AtomicU32 = AtomicU32::new(0);

// 12 workers de periodos distintos
#[embassy_executor::task(pool_size = N)]
async fn worker(i: usize) {
    let period = Duration::from_micros(PERIODS_US[i]);
    let mut next = Instant::now();
    loop {
        next += period;
        Timer::at(next).await;
        let late = Instant::now().saturating_duration_since(next).as_micros() as u32;
        LATE_US[i].fetch_max(late, Relaxed);
        COUNT[i].fetch_add(1, Relaxed);
    }
}

// no duerme y suma 1 a SPINS
#[embassy_executor::task]
async fn spin() {
    loop {
        SPINS.fetch_add(1, Relaxed);
        yield_now().await;
    }
}

// Imprime cada 50ms
#[embassy_executor::task]
async fn chatter() {
    let mut w = Console::writer();
    let mut n: u32 = 0;
    loop {
        Timer::after(Duration::from_millis(50)).await;
        n += 1;
        let _ = writeln!(w, "chatter {n} ................................................");
    }
}

// cada 5s imprime un resumen de los timers
// n: cuántas veces despertó / cuántas veces debería haber despertado, late_max: el peor atraso en microsegundos
#[embassy_executor::task]
async fn report() {
    let mut w = Console::writer();
    loop {
        Timer::after(Duration::from_secs(REPORT_S)).await;
        let _ = writeln!(w, "--- t={}s spins={}", Instant::now().as_secs(), SPINS.swap(0, Relaxed));
        for i in 0..N {
            let n = COUNT[i].swap(0, Relaxed);
            let expected = REPORT_S * 1_000_000 / PERIODS_US[i];
            let tag = if n == 0 { " MUERTO" } else { "" };
            let _ = writeln!(
                w,
                "{i}: {}us n={n}/{expected} late_max={}us{tag}",
                PERIODS_US[i],
                LATE_US[i].swap(0, Relaxed),
            );
        }
    }
}

fn main() {
    libtock::run(|spawner| {
        for i in 0..N {
            spawner.spawn(worker(i).unwrap());
        }
        spawner.spawn(spin().unwrap());
        spawner.spawn(chatter().unwrap());
        spawner.spawn(report().unwrap());
    })
}

